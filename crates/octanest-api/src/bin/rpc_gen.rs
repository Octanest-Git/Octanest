use std::path::PathBuf;

fn main() {
    // CARGO_MANIFEST_DIR = .../crates/octanest-api → repo root is ../..
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out_dir = root.join("packages/api-client/src");
    std::fs::create_dir_all(&out_dir).expect("create api-client src");

    let index = r#"/** AUTO-GENERATED by `cargo run -p octanest-api --bin rpc-gen` — do not edit by hand. */

export const RPC_VERSION = 1 as const;
export const RPC_VERSION_HEADER = "Octanest-RPC-Version" as const;

export type AppError = {
  code: string;
  message: string;
  data?: unknown;
};

export type HealthResponse = {
  status: string;
  version: string;
  database: string;
};

export type EchoRequest = {
  message: string;
};

export type EchoResponse = {
  message: string;
};

export type DbProbeResponse = {
  dialect: string;
  probe_count: number;
  probed_at: string;
};

export type RpcOk<T> = { ok: true; data: T };
export type RpcErr = { ok: false; error: AppError };
export type RpcResult<T> = RpcOk<T> | RpcErr;

export type CreateClientOptions = {
  baseUrl: string;
  fetch?: typeof fetch;
  credentials?: RequestCredentials;
};

async function rpcCall<T>(
  opts: CreateClientOptions,
  procedure: string,
  input: unknown,
): Promise<RpcResult<T>> {
  const fetchFn = opts.fetch ?? fetch;
  const url = `${opts.baseUrl.replace(/\/$/, "")}/api/rpc`;
  const res = await fetchFn(url, {
    method: "POST",
    credentials: opts.credentials ?? "include",
    headers: {
      "content-type": "application/json",
      [RPC_VERSION_HEADER]: String(RPC_VERSION),
    },
    body: JSON.stringify({ procedure, input }),
  });
  return (await res.json()) as RpcResult<T>;
}

export function createClient(opts: CreateClientOptions) {
  return {
    system: {
      health: () => rpcCall<HealthResponse>(opts, "system.health", {}),
      echo: (input: EchoRequest) => rpcCall<EchoResponse>(opts, "system.echo", input),
      dbProbe: () => rpcCall<DbProbeResponse>(opts, "system.db_probe", {}),
    },
  };
}

export type OctanestClient = ReturnType<typeof createClient>;

/** TanStack Query helpers — pass a client from createClient(). */
export function systemHealthQueryOptions(client: OctanestClient) {
  return {
    queryKey: ["system", "health"] as const,
    queryFn: async () => {
      const res = await client.system.health();
      if (!res.ok) throw new Error(`${res.error.code}: ${res.error.message}`);
      return res.data;
    },
  };
}

export function systemEchoMutationOptions(client: OctanestClient) {
  return {
    mutationKey: ["system", "echo"] as const,
    mutationFn: async (input: EchoRequest) => {
      const res = await client.system.echo(input);
      if (!res.ok) throw new Error(`${res.error.code}: ${res.error.message}`);
      return res.data;
    },
  };
}

export function systemDbProbeQueryOptions(client: OctanestClient) {
  return {
    queryKey: ["system", "dbProbe"] as const,
    queryFn: async () => {
      const res = await client.system.dbProbe();
      if (!res.ok) throw new Error(`${res.error.code}: ${res.error.message}`);
      return res.data;
    },
  };
}

/** Alias helpers matching CONTEXT D-21 naming. */
export const queryOptions = {
  systemHealth: systemHealthQueryOptions,
  systemDbProbe: systemDbProbeQueryOptions,
};
export const mutationOptions = { systemEcho: systemEchoMutationOptions };
"#;

    let path = out_dir.join("index.ts");
    std::fs::write(&path, index).expect("write index.ts");
    println!("wrote {}", path.display());
}
